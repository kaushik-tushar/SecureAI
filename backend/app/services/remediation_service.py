"""
SecureAI - Remediation Service

Manages vulnerability remediation workflows.

Features:
- Vulnerability ownership verification
- Remediation recommendation storage
- Suggested code fix storage
- Vulnerability status management
- Resolution timestamp tracking
- Manual review requirements
"""

from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import select
from sqlalchemy.orm import Session

from fastapi import HTTPException, status

from app.models.vulnerability import Vulnerability
from app.models.scan import Scan
from app.models.repository import Repository

from app.schemas.vulnerability import (
    VulnerabilityStatus
)


# ==========================================
# REMEDIATION CONFIGURATION
# ==========================================

ALLOWED_STATUSES = {
    "open",
    "in_progress",
    "resolved",
    "accepted",
    "false_positive"
}

ALLOWED_STATUS_TRANSITIONS = {
    "open": {
        "in_progress",
        "resolved",
        "accepted",
        "false_positive"
    },

    "in_progress": {
        "open",
        "resolved",
        "accepted",
        "false_positive"
    },

    "resolved": {
        "open"
    },

    "accepted": {
        "open"
    },

    "false_positive": {
        "open"
    }
}


# ==========================================
# DATETIME UTILITIES
# ==========================================

def utc_now() -> datetime:

    """
    Returns the current UTC timestamp.
    """

    return datetime.now(timezone.utc)


# ==========================================
# OWNERSHIP VALIDATION
# ==========================================

def get_user_vulnerability(
    db: Session,
    vulnerability_id: int,
    user_id: int
) -> Vulnerability:

    """
    Retrieves a vulnerability belonging to
    the authenticated user.

    Ownership is verified through:

        Vulnerability -> Scan -> Repository -> User

    Raises:
        HTTPException 404 if not found or unauthorized.
    """

    statement = (
        select(Vulnerability)
        .join(
            Scan,
            Vulnerability.scan_id == Scan.id
        )
        .join(
            Repository,
            Scan.repository_id == Repository.id
        )
        .where(
            Vulnerability.id == vulnerability_id,
            Repository.owner_id == user_id
        )
    )

    vulnerability = db.scalar(statement)

    if vulnerability is None:

        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Vulnerability not found."
        )

    return vulnerability


# ==========================================
# GET REMEDIATION DETAILS
# ==========================================

def get_remediation(
    db: Session,
    vulnerability_id: int,
    user_id: int
) -> dict:

    """
    Retrieves remediation information
    for an owned vulnerability.
    """

    vulnerability = get_user_vulnerability(
        db=db,
        vulnerability_id=vulnerability_id,
        user_id=user_id
    )

    return {
        "vulnerability_id": vulnerability.id,
        "recommendation": vulnerability.remediation,
        "suggested_code": vulnerability.remediation_code,
        "explanation": vulnerability.ai_explanation,
        "requires_manual_review": True
    }


# ==========================================
# SAVE REMEDIATION RECOMMENDATION
# ==========================================

def save_remediation(
    db: Session,
    vulnerability_id: int,
    user_id: int,
    recommendation: str,
    suggested_code: Optional[str] = None,
    explanation: Optional[str] = None
) -> dict:

    """
    Stores a remediation recommendation.

    Recommendations may be generated by the
    AI review service or supplied by another
    trusted internal analysis component.

    Suggested code is stored for review.
    It is never automatically applied.
    """

    # --------------------------------------
    # VALIDATE INPUT
    # --------------------------------------

    if not recommendation or not recommendation.strip():

        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Remediation recommendation cannot be empty."
        )

    if len(recommendation) > 20000:

        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Remediation recommendation is too long."
        )

    if suggested_code is not None and len(suggested_code) > 50000:

        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Suggested code exceeds the maximum allowed length."
        )

    if explanation is not None and len(explanation) > 20000:

        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Remediation explanation is too long."
        )

    # --------------------------------------
    # VERIFY OWNERSHIP
    # --------------------------------------

    vulnerability = get_user_vulnerability(
        db=db,
        vulnerability_id=vulnerability_id,
        user_id=user_id
    )

    # --------------------------------------
    # STORE REMEDIATION
    # --------------------------------------

    vulnerability.remediation = recommendation.strip()

    vulnerability.remediation_code = (
        suggested_code.strip()
        if suggested_code
        else None
    )

    if explanation is not None:

        vulnerability.ai_explanation = explanation.strip()

    # --------------------------------------
    # SAVE DATABASE CHANGES
    # --------------------------------------

    try:

        db.commit()

        db.refresh(vulnerability)

    except Exception:

        db.rollback()

        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Unable to save remediation recommendation."
        )

    return {
        "vulnerability_id": vulnerability.id,
        "recommendation": vulnerability.remediation,
        "suggested_code": vulnerability.remediation_code,
        "explanation": vulnerability.ai_explanation,
        "requires_manual_review": True
    }


# ==========================================
# UPDATE VULNERABILITY STATUS
# ==========================================

def update_vulnerability_status(
    db: Session,
    vulnerability_id: int,
    user_id: int,
    new_status: VulnerabilityStatus
) -> Vulnerability:

    """
    Updates the status of an owned vulnerability.

    Tracks the resolution timestamp when a
    vulnerability is marked as resolved.
    """

    # --------------------------------------
    # VALIDATE STATUS
    # --------------------------------------

    if new_status not in ALLOWED_STATUSES:

        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Invalid vulnerability status."
        )

    # --------------------------------------
    # VERIFY OWNERSHIP
    # --------------------------------------

    vulnerability = get_user_vulnerability(
        db=db,
        vulnerability_id=vulnerability_id,
        user_id=user_id
    )

    # --------------------------------------
    # VALIDATE STATUS TRANSITION
    # --------------------------------------

    current_status = vulnerability.status

    allowed_transitions = ALLOWED_STATUS_TRANSITIONS.get(
        current_status,
        set()
    )

    if new_status not in allowed_transitions:

        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=(
                f"Cannot change vulnerability status "
                f"from '{current_status}' to '{new_status}'."
            )
        )

    # --------------------------------------
    # UPDATE STATUS
    # --------------------------------------

    vulnerability.status = new_status

    if new_status == "resolved":

        vulnerability.resolved_at = utc_now()

    else:

        vulnerability.resolved_at = None

    # --------------------------------------
    # SAVE DATABASE CHANGES
    # --------------------------------------

    try:

        db.commit()

        db.refresh(vulnerability)

        return vulnerability

    except Exception:

        db.rollback()

        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Unable to update vulnerability status."
        )


# ==========================================
# GET VULNERABILITY REMEDIATION SUMMARY
# ==========================================

def get_remediation_summary(
    db: Session,
    vulnerability_id: int,
    user_id: int
) -> dict:

    """
    Returns a complete remediation summary
    for an owned vulnerability.
    """

    vulnerability = get_user_vulnerability(
        db=db,
        vulnerability_id=vulnerability_id,
        user_id=user_id
    )

    return {
        "vulnerability_id": vulnerability.id,
        "title": vulnerability.title,
        "severity": vulnerability.severity,
        "status": vulnerability.status,
        "description": vulnerability.description,
        "impact": vulnerability.impact,
        "recommendation": vulnerability.remediation,
        "suggested_code": vulnerability.remediation_code,
        "ai_explanation": vulnerability.ai_explanation,
        "resolved_at": vulnerability.resolved_at,
        "requires_manual_review": True
    }